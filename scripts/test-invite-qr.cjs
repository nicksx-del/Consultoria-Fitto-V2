const { readFileSync } = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
const { toQR } = require('toqr');
const jsQR = require('jsqr');
const compiled = ts.transpileModule(readFileSync('src/features/relationships/parseInvite.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const moduleExports = {};
new Function('exports', compiled)(moduleExports);
const { parseInvite } = moduleExports;
const origin = 'https://consultoria-fitto-v2.vercel.app';
const token = 'a'.repeat(64);
const url = `${origin}/convite?token=${token}`;
assert.equal(parseInvite('123 456', origin), '123456');
assert.equal(parseInvite(url, origin), token);
assert.equal(parseInvite(`${url}&ignored=1`, origin), token);
for (const invalid of [`https://example.com/convite?token=${token}`, `javascript:alert(1)`, `${origin}/perfil?token=${token}`, `${origin}/convite?token=short`, 'not a QR invitation']) assert.equal(parseInvite(invalid, origin), null);
const matrix = toQR(url); const n = Math.sqrt(matrix.length); const scale = 6; const side = (n + 8) * scale;
const rgba = new Uint8ClampedArray(side * side * 4).fill(255);
for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) if (matrix[y * n + x]) for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) { const i = (((y + 4) * scale + dy) * side + (x + 4) * scale + dx) * 4; rgba[i] = rgba[i + 1] = rgba[i + 2] = 0; }
const decoded = jsQR(rgba, side, side);
assert.equal(decoded?.data, url);
assert.equal(parseInvite(decoded.data, origin), token);
console.log('PASS: QR generated by Fitto decodes correctly; valid codes and links accepted; foreign links and invalid payloads rejected.');
